#!/usr/bin/env python3
"""
Validate annotated dataset for quality before fine-tuning.
Usage: python validate_dataset.py
"""

import json
import sys
from pathlib import Path
from collections import Counter, defaultdict

def validate_dataset():
    """Validate annotated dataset quality."""
    
    input_file = Path(r"E:\Ai agent\fine-tuning\processed_data\annotation_tasks_labeled.jsonl")
    report_file = Path(r"E:\Ai agent\fine-tuning\results\validation_report.json")
    
    if not input_file.exists():
        print(f"❌ Input file not found: {input_file}")
        print("   Expected file: annotation_tasks_labeled.jsonl")
        print("   (Generated by annotate_dataset.py)")
        return 1
    
    print("🔍 Validating dataset...\n")
    
    examples = []
    errors = []
    warnings = []
    
    with open(input_file, encoding='utf-8') as f:
        for i, line in enumerate(f, 1):
            try:
                example = json.loads(line)
                examples.append((i, example))
            except json.JSONDecodeError as e:
                errors.append(f"Line {i}: Invalid JSON - {e}")
    
    if not examples:
        print("❌ No examples found in dataset!")
        return 1
    
    print(f"📊 Loaded {len(examples)} examples\n")
    
    # Validation checks
    stats = {
        "total_examples": len(examples),
        "valid_examples": 0,
        "missing_fields": defaultdict(int),
        "action_types": Counter(),
        "difficulties": Counter(),
        "domain_tags": Counter(),
        "avg_confidence": 0.0,
        "avg_instruction_length": 0.0,
        "avg_context_size": 0.0,
    }
    
    confidences = []
    instruction_lengths = []
    context_sizes = []
    
    for line_no, example in examples:
        is_valid = True
        
        # Check required fields
        required_fields = {
            "instruction": "input",
            "action_type": "output.action_type",
            "difficulty": "annotation.difficulty",
            "confidence": "annotation.confidence"
        }
        
        for field, path in required_fields.items():
            if not example.get(field.split(".")[0]):
                warnings.append(f"Line {line_no}: Missing top-level '{field}'")
                is_valid = False
        
        # Validate action type
        action_type = example.get("output", {}).get("action_type", "")
        valid_actions = ["find_entities", "count_entities", "extract_text_data", "analyze_block_attributes"]
        if action_type not in valid_actions:
            warnings.append(f"Line {line_no}: Invalid action_type '{action_type}'. Must be one of: {valid_actions}")
            is_valid = False
        else:
            stats["action_types"][action_type] += 1
        
        # Validate difficulty
        difficulty = example.get("annotation", {}).get("difficulty", "")
        valid_difficulties = ["easy", "medium", "hard"]
        if difficulty not in valid_difficulties:
            warnings.append(f"Line {line_no}: Invalid difficulty '{difficulty}'. Must be: {valid_difficulties}")
            is_valid = False
        else:
            stats["difficulties"][difficulty] += 1
        
        # Validate confidence
        confidence = example.get("annotation", {}).get("confidence", 0)
        if not isinstance(confidence, (int, float)) or not (0 <= confidence <= 1):
            warnings.append(f"Line {line_no}: Confidence must be 0.0-1.0, got {confidence}")
            is_valid = False
        else:
            confidences.append(confidence)
        
        # Check instruction
        instruction = example.get("instruction", "")
        if not instruction or len(instruction) < 5:
            warnings.append(f"Line {line_no}: Instruction too short or missing")
            is_valid = False
        else:
            instruction_lengths.append(len(instruction))
        
        # Check domain tags
        tags = example.get("annotation", {}).get("domain_tags", [])
        if not tags:
            warnings.append(f"Line {line_no}: No domain tags specified")
        else:
            for tag in tags:
                stats["domain_tags"][tag] += 1
        
        if is_valid:
            stats["valid_examples"] += 1
        
        context = example.get("input", {}).get("context", {})
        context_size = (
            context.get("blocks_count", 0) +
            context.get("texts_count", 0) +
            context.get("lines_count", 0) +
            context.get("polylines_count", 0)
        )
        context_sizes.append(context_size)
    
    # Calculate averages
    if confidences:
        stats["avg_confidence"] = sum(confidences) / len(confidences)
    if instruction_lengths:
        stats["avg_instruction_length"] = sum(instruction_lengths) / len(instruction_lengths)
    if context_sizes:
        stats["avg_context_size"] = sum(context_sizes) / len(context_sizes)
    
    # Print results
    print("✅ VALIDATION RESULTS:\n")
    print(f"  Total examples: {stats['total_examples']}")
    print(f"  Valid examples: {stats['valid_examples']} ({stats['valid_examples']*100//stats['total_examples']}%)")
    print(f"  Average confidence: {stats['avg_confidence']:.2f}")
    print(f"  Average instruction length: {stats['avg_instruction_length']:.0f} chars")
    print(f"  Average context size: {stats['avg_context_size']:.0f} entities\n")
    
    print("📊 ACTION TYPES:\n")
    for action, count in stats["action_types"].most_common():
        percentage = count * 100 // stats['valid_examples'] if stats['valid_examples'] > 0 else 0
        print(f"  {action}: {count} ({percentage}%)")
    
    print("\n📈 DIFFICULTY DISTRIBUTION:\n")
    for difficulty, count in sorted(stats["difficulties"].items()):
        percentage = count * 100 // stats['valid_examples'] if stats['valid_examples'] > 0 else 0
        print(f"  {difficulty}: {count} ({percentage}%)")
        
        # Check recommendations
        if difficulty == "easy" and percentage < 20:
            warnings.append(f"⚠️  Only {percentage}% easy examples. Recommend 25-30% for better learning")
        elif difficulty == "hard" and percentage > 30:
            warnings.append(f"⚠️  {percentage}% hard examples. Recommend max 20% to avoid overfitting")
    
    print("\n🏷️  TOP DOMAIN TAGS:\n")
    for tag, count in stats["domain_tags"].most_common(10):
        print(f"  {tag}: {count}")
    
    # Print warnings if any
    if warnings:
        print(f"\n⚠️  WARNINGS ({len(warnings)}):\n")
        for warning in warnings[:20]:  # Show first 20
            print(f"  {warning}")
        if len(warnings) > 20:
            print(f"  ... and {len(warnings) - 20} more")
    
    if errors:
        print(f"\n❌ ERRORS ({len(errors)}):\n")
        for error in errors[:10]:
            print(f"  {error}")
        if len(errors) > 10:
            print(f"  ... and {len(errors) - 10} more")
    
    # Save report
    report = {
        "timestamp": Path(input_file).stat().st_mtime,
        "statistics": dict(stats),
        "action_types": dict(stats["action_types"]),
        "difficulties": dict(stats["difficulties"]),
        "domain_tags": dict(stats["domain_tags"]),
        "warnings": warnings,
        "errors": errors,
        "recommendations": [
            "✅ Dataset quality good - ready for training" if len(warnings) < 10 else "⚠️  Address warnings before training",
            "✅ Action type distribution reasonable" if min(v for v in stats["action_types"].values() if v > 0) > 1 else "⚠️  Some action types underrepresented",
            "✅ Difficulty distribution appropriate" if 20 <= stats["difficulties"].get("medium", 0) * 100 // stats['valid_examples'] <= 60 else "⚠️  Adjust difficulty distribution"
        ]
    }
    
    with open(report_file, "w", encoding='utf-8') as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    
    print(f"\n📁 Report saved to: {report_file}")
    
    # Return appropriate code
    if stats['valid_examples'] < stats['total_examples'] * 0.8:
        return 1
    return 0

def main():
    return validate_dataset()

if __name__ == "__main__":
    sys.exit(main())
